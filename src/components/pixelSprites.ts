export type PixelMatrix = ReadonlyArray<ReadonlyArray<number | null>>;

// Literal rows are the sprite source, decoded once (no images or network assets).
function pixels(rows: readonly string[]): PixelMatrix {
  if (rows.some((row) => row.length !== rows[0].length || /[^0-9A-F.]/.test(row))) {
    throw new Error("Invalid pixel sprite matrix");
  }
  return rows.map((row) => Array.from(row, (pixel) => pixel === "." ? null : parseInt(pixel, 16)));
}

